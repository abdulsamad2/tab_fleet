'use strict';

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('fleet', {
  getInitial: () => ipcRenderer.invoke('get-initial'),
  validate: (config) => ipcRenderer.invoke('validate', config),
  launch: (config) => ipcRenderer.invoke('launch', config),
  getSnippets: () => ipcRenderer.invoke('snippets:get'),
  saveSnippets: (list) => ipcRenderer.invoke('snippets:save', list),
  listProfiles: () => ipcRenderer.invoke('profiles:list'),
  importProfilesFile: () => ipcRenderer.invoke('profiles:import-file'),
  exportProfilesFile: () => ipcRenderer.invoke('profiles:export-file'),
  importProfilesText: (text) => ipcRenderer.invoke('profiles:import-text', text),
  deleteProfiles: (ids) => ipcRenderer.invoke('profiles:delete', ids),
  saveProfile: (input) => ipcRenderer.invoke('profiles:save', input),
  openGoogleSheet: (url) => ipcRenderer.invoke('profiles:open-sheet', url),
  importFromSheet: (url) => ipcRenderer.invoke('profiles:import-sheet', url),
  command: (name, tabId, arg) => ipcRenderer.send('command', name, tabId, arg),
  invoke: (name, tabId, arg) => ipcRenderer.invoke('invoke', name, tabId, arg),
  setInsets: (insets) => ipcRenderer.send('layout-insets', insets),
  onState: (listener) => ipcRenderer.on('state', (_event, state) => listener(state)),
  onFocusAddress: (listener) => ipcRenderer.on('focus-address', () => listener()),
  onTogglePanel: (listener) => ipcRenderer.on('toggle-panel', (_event, section) => listener(section)),
  onProfilesChanged: (listener) => ipcRenderer.on('profiles-changed', () => listener()),
  onProfilesImported: (listener) => ipcRenderer.on('profiles-imported', (_event, result) => listener(result)),
  onOpenSheetImport: (listener) => ipcRenderer.on('open-sheet-import', () => listener()),
  onUpdateStatus: (listener) => ipcRenderer.on('update-status', (_event, info) => listener(info)),
  getUpdateInfo: () => ipcRenderer.invoke('update:get-info'),
  checkForUpdate: () => ipcRenderer.invoke('update:check-now'),
  downloadUpdate: () => ipcRenderer.invoke('update:download'),
  installUpdate: () => ipcRenderer.invoke('update:install-now'),
  saveSettings: (settings) => ipcRenderer.invoke('settings:save', settings),
  onOpenSettings: (listener) => ipcRenderer.on('open-settings', () => listener()),
  setOverlay: (open) => ipcRenderer.send('overlay', open),
  getSyncSettings: () => ipcRenderer.invoke('sync:get-settings'),
  saveSyncSettings: (input) => ipcRenderer.invoke('sync:save-settings', input),
  testSync: () => ipcRenderer.invoke('sync:test'),
  listOrders: (params) => ipcRenderer.invoke('orders:list', params),
  onOpenOrders: (listener) => ipcRenderer.on('open-orders', () => listener()),
  onNotice: (listener) => ipcRenderer.on('notice', (_event, text) => listener(text)),
  switchGroup: (input) => ipcRenderer.invoke('groups:switch', input),
  renameGroup: (input) => ipcRenderer.invoke('groups:rename', input),
  restartForGroup: () => ipcRenderer.invoke('groups:restart'),
});
